import type { DoseEventType, DoseStatus } from "./types";

/**
 * Dose state machine. Pure and UI-independent.
 *
 * Product truth rules (from the spec):
 *  - "notified" means a reminder was sent, not that anyone saw it.
 *  - "acknowledged" means seen, not that medication was taken.
 *  - "reported_taken" is a SELF-REPORT, never verified ingestion.
 *  - "unknown" stays unknown; it is never silently converted to taken/missed.
 */

/** Statuses a patient has actively answered. */
export const RESPONDED: ReadonlySet<DoseStatus> = new Set([
  "reported_taken",
  "reported_skipped",
  "unknown",
]);

/** Statuses counted as "unresolved" for dashboards and escalation. */
export const UNRESOLVED: ReadonlySet<DoseStatus> = new Set([
  "scheduled",
  "notified",
  "acknowledged",
  "snoozed",
  "missed_by_policy",
]);

const EVENT_TO_STATUS: Record<DoseEventType, DoseStatus> = {
  notified: "notified",
  acknowledged: "acknowledged",
  reported_taken: "reported_taken",
  reported_skipped: "reported_skipped",
  snoozed: "snoozed",
  reported_unsure: "unknown",
  missed_by_policy: "missed_by_policy",
  cancelled: "cancelled",
  reinstated: "scheduled",
};

/** Event types a human may submit. System events are generated by the worker. */
export const USER_EVENT_TYPES = [
  "acknowledged",
  "reported_taken",
  "reported_skipped",
  "snoozed",
  "reported_unsure",
] as const satisfies readonly DoseEventType[];
export type UserEventType = (typeof USER_EVENT_TYPES)[number];

export const SYSTEM_EVENT_TYPES = [
  "notified",
  "missed_by_policy",
  "cancelled",
  "reinstated",
] as const satisfies readonly DoseEventType[];

export class InvalidTransitionError extends Error {
  readonly status = 409;
  constructor(message: string) {
    super(message);
    this.name = "InvalidTransitionError";
  }
}

export interface TransitionInput {
  current: DoseStatus;
  event: DoseEventType;
  /** True when the event originates from a person, false for the worker. */
  byUser: boolean;
}

/**
 * Returns the next status, or throws InvalidTransitionError.
 *
 * Rules:
 *  - cancelled is terminal; nothing changes it.
 *  - A person may always (re)answer an active dose; each answer is a new event
 *    and the previous history is preserved (a correction is just a new event).
 *  - The system may only advance a dose that is still unresolved, so it can
 *    never overwrite a patient's own answer.
 */
export function nextStatus({ current, event, byUser }: TransitionInput): DoseStatus {
  // A schedule change (e.g. medication resumed) may bring a cancelled dose back.
  if (event === "reinstated" && !byUser && current === "cancelled") return "scheduled";
  if (current === "cancelled") {
    throw new InvalidTransitionError("This dose was cancelled and can no longer be changed.");
  }
  if (!byUser) {
    if (!UNRESOLVED.has(current)) {
      throw new InvalidTransitionError("A person has already answered this dose.");
    }
    if (event === "notified" && current !== "scheduled" && current !== "snoozed") {
      throw new InvalidTransitionError("Already notified.");
    }
    if (event === "missed_by_policy" && current === "missed_by_policy") {
      throw new InvalidTransitionError("Already marked.");
    }
    return EVENT_TO_STATUS[event];
  }
  if (!(USER_EVENT_TYPES as readonly string[]).includes(event)) {
    throw new InvalidTransitionError("That action is not available to people.");
  }
  return EVENT_TO_STATUS[event];
}

