"use client";
import { useRef, useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { Alert } from "@/components/ui/alert";
import { Button } from "@/components/ui/button";
import { Field, Select, Textarea } from "@/components/ui/field";
import { useAnnounce } from "@/components/a11y/announcer";
import { ReadAloud } from "@/components/a11y/read-aloud";
import { api, errorMessage } from "@/lib/client/api";
import { SECTIONS, SECTION_TITLE, type SectionKey } from "@/lib/domain/handover";
import { fmtDateTime } from "@/lib/format";

export interface HandoverItemView { id: string; section: SectionKey; text: string; attention: boolean }
export interface HandoverDetail {
  id: string; status: "draft" | "shared"; createdByName: string; createdAt: string; periodHours: number; periodStart: string; periodEnd: string;
  items: HandoverItemView[]; omitted: string[]; summaryLines: { text: string; refs: string[] }[]; summarySource: "ai" | "template";
  note: string; recipientUid: string | null; recipientName: string | null; sharedAt: string | null; acknowledgedAt: string | null;
  lastActivity: { text: string; at: string } | null;
}

export function HandoverView({ patientId, h, recipients, timezone, isAuthor, isRecipient }: {
  patientId: string; h: HandoverDetail; recipients: { uid: string; displayName: string }[]; timezone: string; isAuthor: boolean; isRecipient: boolean;
}) {
  const router = useRouter();
  const announce = useAnnounce();
  const [note, setNote] = useState(h.note);
  const [recipient, setRecipient] = useState("");
  const [busy, setBusy] = useState<string | null>(null);
  const [msg, setMsg] = useState<{ kind: "error" | "success"; text: string } | null>(null);
  const msgRef = useRef<HTMLDivElement>(null);
  const draft = h.status === "draft" && isAuthor;

  const say = (kind: "error" | "success", text: string) => { setMsg({ kind, text }); announce(text, kind === "error" ? "assertive" : "polite"); requestAnimationFrame(() => msgRef.current?.focus()); };
  async function run(key: string, fn: () => Promise<unknown>, ok: string, after?: () => void) {
    setBusy(key); setMsg(null);
    try { await fn(); say("success", ok); if (after) after(); else router.refresh(); } catch (e) { say("error", errorMessage(e)); } finally { setBusy(null); }
  }

  const base = `/api/patients/${patientId}/handovers/${h.id}`;
  const bySection = SECTIONS.map((s) => [s, h.items.filter((i) => i.section === s)] as const).filter(([, items]) => items.length);
  const attention = h.items.filter((i) => i.attention);
  const summary = h.summaryLines.map((l) => l.text).join(" ");

  return (
    <div className="space-y-6">
      <div ref={msgRef} tabIndex={-1} aria-live="polite">{msg && <Alert variant={msg.kind} title={msg.text} />}</div>

      <Alert variant="info" title="Based on your records, not on assumptions.">
        {h.summarySource === "ai" ? "The summary was written by AI from the facts below and checked against them. " : "The summary below is a plain list of the facts. "}
        Doses marked taken are what the patient reported, not proof. Anything unresolved stays unresolved.
      </Alert>

      <section aria-labelledby="sum-h" className="space-y-2 rounded-xl border-2 p-4">
        <h2 id="sum-h" className="text-xl font-bold">Care update</h2>
        <p className="text-sm text-muted-foreground">
          Covers the last {h.periodHours} hours ({fmtDateTime(h.periodStart, timezone)} to {fmtDateTime(h.periodEnd, timezone)}).
          {h.summarySource === "ai" ? " Summary generated by AI." : ""}
        </p>
        <ul className="list-disc space-y-1 pl-6 text-lg">{h.summaryLines.map((l, i) => <li key={i}>{l.text}</li>)}</ul>
        {h.note && <div className="rounded-xl bg-muted p-3"><p className="font-bold">Note from {h.createdByName}</p><p className="whitespace-pre-wrap">{h.note}</p></div>}
        <p className="font-semibold">Last updated by: {h.createdByName}{h.lastActivity ? `. ${h.lastActivity.text} at ${fmtDateTime(h.lastActivity.at, timezone)}.` : "."}</p>
        <ReadAloud text={`${summary} ${h.note}`} label="Read this update aloud" />
      </section>

      {h.omitted.length > 0 && <Alert variant="warning" title="Not covered in this handover">The author could not see: {h.omitted.join(", ")}.</Alert>}

      {attention.length > 0 && (
        <section aria-labelledby="att-h" className="space-y-2 rounded-xl border-2 border-warning bg-warning-bg p-4">
          <h2 id="att-h" className="text-xl font-bold">Needs attention ({attention.length})</h2>
          <ul className="list-disc space-y-1 pl-6">{attention.map((i) => <li key={i.id}>{i.text}</li>)}</ul>
        </section>
      )}

      <section aria-labelledby="facts-h" className="space-y-3">
        <h2 id="facts-h" className="text-xl font-bold">The facts behind it</h2>
        {bySection.length === 0 && <p>Nothing to report for this period.</p>}
        {bySection.map(([s, items]) => (
          <div key={s}>
            <h3 className="text-lg font-bold">{SECTION_TITLE[s]}</h3>
            <ul className="list-disc space-y-1 pl-6">{items.map((i) => <li key={i.id}>{i.text}</li>)}</ul>
          </div>
        ))}
      </section>

      {draft && (
        <section aria-labelledby="share-h" className="space-y-4 rounded-xl border-2 p-4">
          <h2 id="share-h" className="text-xl font-bold">Review and share</h2>
          <p>This draft is private to you until you share it.</p>
          <Field id="ho-note" label="Add your own note" hint="For things only you know. It is shown separately from the generated summary.">
            {(p) => <Textarea {...p} rows={3} maxLength={1000} value={note} onChange={(e) => setNote(e.target.value)} />}
          </Field>
          <div className="flex flex-wrap gap-2">
            <Button type="button" variant="outline" disabled={busy !== null || note === h.note} onClick={() => run("note", () => api(base, { method: "PATCH", body: { note } }), "Note saved.")}>Save note</Button>
            <Button type="button" variant="outline" disabled={busy !== null} onClick={() => run("refresh", () => api(`${base}/refresh`, { method: "POST" }), "Updated with the latest records.", () => router.push(`/patients/${patientId}/handover`))}>Refresh from latest records</Button>
          </div>
          <Field id="ho-who" label="Hand over to" required hint="Only people allowed to see everything in this handover are listed as able to receive it.">
            {(p) => (
              <Select {...p} value={recipient} onChange={(e) => setRecipient(e.target.value)}>
                <option value="">Choose a person…</option>
                {recipients.map((r) => <option key={r.uid} value={r.uid}>{r.displayName}</option>)}
              </Select>
            )}
          </Field>
          <div className="flex flex-wrap gap-2">
            <Button type="button" disabled={busy !== null || !recipient} onClick={() => run("share", async () => { if (note !== h.note) await api(base, { method: "PATCH", body: { note } }); await api(`${base}/share`, { body: { recipientUid: recipient } }); }, "Handover shared.")}>
              {busy === "share" ? "Sharing…" : "Share this handover"}
            </Button>
            <Button type="button" variant="outline" disabled={busy !== null} onClick={() => window.confirm("Delete this draft?") && run("del", () => api(base, { method: "DELETE" }), "Draft deleted.", () => router.push(`/patients/${patientId}/handover`))}>Delete draft</Button>
          </div>
        </section>
      )}

      {h.status === "shared" && (
        <section aria-labelledby="st-h" className="space-y-3 rounded-xl border-2 p-4">
          <h2 id="st-h" className="text-xl font-bold">Hand-over status</h2>
          <p>Shared with <strong>{h.recipientName}</strong>{h.sharedAt ? ` on ${fmtDateTime(h.sharedAt, timezone)}` : ""}.</p>
          {h.acknowledgedAt ? <Alert variant="success" title={`Acknowledged on ${fmtDateTime(h.acknowledgedAt, timezone)}.`} /> : <p className="font-semibold">Waiting for {h.recipientName} to acknowledge.</p>}
          {isRecipient && !h.acknowledgedAt && (
            <Button type="button" disabled={busy !== null} onClick={() => run("ack", () => api(`${base}/acknowledge`, { method: "POST" }), "Thank you. The handover is acknowledged.")}>I have read this handover</Button>
          )}
        </section>
      )}
      <Link href={`/patients/${patientId}/handover`} className="inline-flex min-h-12 items-center font-semibold underline">Back to handovers</Link>
    </div>
  );
}
